#!/usr/bin/env python3
"""Rebuild the release list in website/changelog.html from the game repository.

Each published desktop release (tag vX.Y.Z) gets its written release notes from
releases/desktop/X.Y.Z.md (or a dated *-vX.Y.Z.md) in the game repository. A release
without notes lists the summaries of the commits since the previous published release,
leaving out housekeeping commits. Tags that were never published fold into the next
published release.

The game's release workflow runs this after publishing, so the page stays current:

    gh api --paginate "repos/OWNER/REPO/releases?per_page=100" \
        --jq '.[] | select(.draft == false and .prerelease == false) | {tag: .tag_name, published: .published_at}' \
        > releases.jsonl
    scripts/build-changelog.py --game-repo ../dunecity --releases releases.jsonl

Without --releases every vX.Y.Z tag counts as published, dated by its commit.
"""

from __future__ import annotations

import argparse
import datetime
import html
import json
import re
import subprocess
import sys
from pathlib import Path

START = "<!-- CHANGELOG:START (generated by scripts/build-changelog.py; do not edit by hand) -->"
END = "<!-- CHANGELOG:END -->"
REPO_URL = "https://github.com/dunecity-project/dunecity"
TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")

# Commit summaries that say nothing to a player.
HOUSEKEEPING = re.compile(
    r"\[skip ci\]"
    r"|^(docs?|chore|ci|tests?|build|style|refactor)(\([^)]*\))?!?:"
    r"|^(Merge|Record|Revert|WIP)\b"
    r"|release notes"
    r"|^(bump|Bump) (the )?version"
    r"|^v?\d+\.\d+\.\d+$",
)
CONVENTIONAL = re.compile(r"^(feat|fix|perf)(\([^)]*\))?!?:\s*")
VERSION_PREFIX = re.compile(r"^v?\d+\.\d+\.\d+\s*[:—–-]\s*", re.IGNORECASE)
VERSION_SUFFIX = re.compile(r"\s*(\(v?\d+\.\d+\.\d+\)|\bin v?\d+\.\d+\.\d+|;\s*bump v?\d+\.\d+\.\d+)\s*$")
# Build, CI and developer-process work: real changes, but not to the game.
INTERNAL = re.compile(
    r"\b(CI|ci|runners?|vcpkg|ccache|workflows?|homebrew|Homebrew|ninja|agents?|todo-batch|probes?|staging)\b"
    r"|(?i:^(repo|release|ci\+release|tornie/[\w-]+):|\bbump(ed)? (to|version)\b)",
)
SKIPPED_SECTIONS = re.compile(r"verification|checksum|sha-?256|assets?$", re.IGNORECASE)
MAX_COMMITS = 12


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True,
                          capture_output=True, text=True).stdout


def version_key(tag: str) -> tuple[int, int, int]:
    match = TAG.match(tag)
    assert match
    return tuple(int(part) for part in match.groups())  # type: ignore[return-value]


def published_releases(repo: Path, releases_file: Path | None) -> list[tuple[str, str]]:
    tags = {tag for tag in git(repo, "tag", "-l", "v*").split() if TAG.match(tag)}
    if releases_file is None:
        dates = {tag: git(repo, "log", "-1", "--format=%cs", tag).strip() for tag in tags}
    else:
        dates = {}
        for line in releases_file.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            entry = json.loads(line)
            if entry["tag"] in tags:
                dates[entry["tag"]] = entry["published"][:10]
    return sorted(dates.items(), key=lambda item: version_key(item[0]))


def notes_files(repo: Path) -> dict[tuple[int, int, int], Path]:
    """Release notes by version: X.Y.Z.md, else the latest dated *-vX.Y.Z.md."""
    folder = repo / "releases" / "desktop"
    found: dict[tuple[int, int, int], Path] = {}
    for pattern, name in (("*-v*.md", r"-v(\d+)\.(\d+)\.(\d+)\.md$"), ("*.md", r"^(\d+)\.(\d+)\.(\d+)\.md$")):
        for path in sorted(folder.glob(pattern)):
            match = re.search(name, path.name)
            if match:
                found[tuple(int(part) for part in match.groups())] = path  # type: ignore[index]
    return found


def inline(text: str) -> str:
    parts = re.split(r"(`[^`]+`)", text)
    out = []
    for part in parts:
        if part.startswith("`") and part.endswith("`") and len(part) > 1:
            out.append(f"<code>{html.escape(part[1:-1])}</code>")
            continue
        escaped = html.escape(part, quote=False)
        escaped = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", escaped)
        escaped = re.sub(
            r"\[([^\]]+)\]\((https?://[^)\s]+)\)",
            lambda m: f'<a href="{html.escape(m.group(2))}">{m.group(1)}</a>',
            escaped,
        )
        out.append(escaped)
    return "".join(out)


def render_notes(text: str) -> str:
    """Small Markdown subset used by the release notes: headings, paragraphs, bullets."""
    blocks: list[str] = []
    paragraph: list[str] = []
    items: list[list[str]] = []
    skipping = False

    def flush() -> None:
        if paragraph:
            blocks.append(f"<p>{inline(' '.join(paragraph))}</p>")
            paragraph.clear()
        if items:
            blocks.append("<ul>" + "".join(f"<li>{inline(' '.join(item))}</li>" for item in items) + "</ul>")
            items.clear()

    lines = text.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    for raw in lines:
        line = raw.rstrip()
        heading = re.match(r"^#{2,6}\s+(.*)$", line)
        if heading:
            flush()
            skipping = bool(SKIPPED_SECTIONS.search(heading.group(1)))
            if not skipping:
                blocks.append(f"<h4>{inline(heading.group(1))}</h4>")
            continue
        if skipping:
            continue
        if not line.strip():
            flush()
            continue
        bullet = re.match(r"^\s*[-*]\s+(.*)$", line)
        if bullet:
            if paragraph:
                flush()
            items.append([bullet.group(1)])
        elif items and raw.startswith((" ", "\t")):
            items[-1].append(line.strip())
        else:
            if items:
                flush()
            paragraph.append(line.strip())
    flush()
    return "\n".join(blocks)


def commit_summaries(repo: Path, previous: str | None, tag: str) -> list[str]:
    span = f"{previous}..{tag}" if previous else tag
    seen: set[str] = set()
    summaries = []
    for subject in git(repo, "log", "--no-merges", "--format=%s", span).splitlines():
        subject = VERSION_PREFIX.sub("", subject.strip())
        if not subject or HOUSEKEEPING.search(subject) or INTERNAL.search(subject):
            continue
        subject = VERSION_SUFFIX.sub("", VERSION_PREFIX.sub("", CONVENTIONAL.sub("", subject))).strip().rstrip(".")
        if not subject:
            continue
        subject = subject[0].upper() + subject[1:]
        if subject.lower() in seen:
            continue
        seen.add(subject.lower())
        summaries.append(subject)
    return summaries


def long_date(iso: str) -> str:
    day = datetime.date.fromisoformat(iso)
    return f"{day.day} {day.strftime('%B %Y')}"


def render(repo: Path, releases: list[tuple[str, str]]) -> str:
    sections = []
    notes = notes_files(repo)
    previous: str | None = None
    for tag, date in releases:
        version = tag[1:]
        # Versions built but never tagged or published ship in this release: show their notes too.
        low = version_key(previous) if previous else (0, 0, 0)
        covered = sorted((key for key in notes if low < key <= version_key(tag)), reverse=True)
        if covered:
            parts = []
            for key in covered:
                if key != version_key(tag):
                    parts.append("<h4>Also includes {}.{}.{}</h4>".format(*key))
                parts.append(render_notes(notes[key].read_text(encoding="utf-8")))
            body = "\n".join(parts)
        else:
            summaries = commit_summaries(repo, previous, tag)
            shown = summaries[:MAX_COMMITS]
            if shown:
                body = "<ul>" + "".join(f"<li>{inline(s)}</li>" for s in shown) + "</ul>"
            else:
                body = "<p>Maintenance release.</p>"
            if len(summaries) > len(shown):
                more = len(summaries) - len(shown)
                body += f'<p class="release-more">and {more} more change{"s" if more != 1 else ""}.</p>'
        compare = f"{REPO_URL}/compare/{previous}...{tag}" if previous else f"{REPO_URL}/commits/{tag}"
        sections.append(
            f'<section class="release" id="{tag}">\n'
            f'<h3><a href="#{tag}">Dune City {version}</a> <time datetime="{date}">{long_date(date)}</time></h3>\n'
            f"{body}\n"
            f'<p class="release-links"><a href="{REPO_URL}/releases/tag/{tag}">Downloads</a> · '
            f'<a href="{compare}">All code changes</a></p>\n'
            f"</section>"
        )
        previous = tag
    sections.reverse()
    return "\n".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game-repo", type=Path, required=True)
    parser.add_argument("--releases", type=Path, help="JSON lines {tag, published} of published releases")
    parser.add_argument("--page", type=Path,
                        default=Path(__file__).resolve().parents[1] / "website" / "changelog.html")
    args = parser.parse_args()

    releases = published_releases(args.game_repo, args.releases)
    if not releases:
        print("no published releases found", file=sys.stderr)
        return 1
    page = args.page.read_text(encoding="utf-8")
    start, end = page.find(START), page.find(END)
    if start < 0 or end < start:
        print(f"{args.page}: changelog markers not found", file=sys.stderr)
        return 1
    generated = render(args.game_repo, releases)
    args.page.write_text(page[: start + len(START)] + "\n" + generated + "\n" + page[end:], encoding="utf-8")
    print(f"{args.page}: {len(releases)} releases, newest {releases[-1][0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
